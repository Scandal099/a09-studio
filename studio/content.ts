export function formatIdToServiceOption(formatId: FormatId | null): ServiceOption {
  if (formatId === "landing") return SERVICE_OPTIONS[0];
  if (formatId === "website") return SERVICE_OPTIONS[1];
  if (formatId === "redesign") return SERVICE_OPTIONS[2];
  if (formatId === "crm") return SERVICE_OPTIONS[3];
  if (formatId === "catalog") return SERVICE_OPTIONS[4];
  if (formatId === "audit") return SERVICE_OPTIONS[5];
  return SERVICE_OPTIONS[6];
}
